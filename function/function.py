# Python Functions
# A function is a block of code that we can reuse.

# Simple function
def say_hello():
    print("Hello, welcome to Python!")


say_hello()


# Function with a parameter
def greet(name):
    print("Hello", name)


greet("Mohammed")
greet("Ali")


# Function with two parameters
def add_numbers(a, b):
    print("Sum:", a + b)
